# Суфікси абстрактних іменників (евристика «абстрактність»)
ABSTRACT_SUFFIXES = ("ість", "ості", "істю", "ння", "нню", "ння", "ція", "ції", "цію", "ізм", "ізму", "ство", "ства", "ацій")


def is_abstract(word: str) -> bool:
    w = word.lower()
    return len(w) > 6 and w.endswith(ABSTRACT_SUFFIXES)


def count_phrases(text_lower: str, phrases: list[str]) -> dict[str, int]:
    """Рахує входження фраз з урахуванням меж слів."""
    out: dict[str, int] = {}
    for ph in phrases:
        pattern = r"(?<![\w])" + re.escape(ph) + r"(?![\w])"
        n = len(re.findall(pattern, text_lower))
        if n:
            out[ph] = n
    return out


def starts_with_phrase(sentence_lower: str, phrases: list[str]) -> str | None:
    s = sentence_lower.lstrip(" -—–«\"'(")
    for ph in phrases:
        if s.startswith(ph) and (len(s) == len(ph) or not s[len(ph)].isalnum()):
            return ph
    return None


def truncate(text: str, n: int = 200) -> str:
    text = " ".join(text.split())
    return text if len(text) <= n else text[: n - 1].rstrip() + "…"
