# Скорочення, після яких крапка не завершує речення.
ABBREVIATIONS = {
    "т", "д", "п", "ін", "ім", "р", "рр", "ст", "млн", "млрд", "тис", "грн", "дол",
    "див", "напр", "проф", "акад", "вул", "м", "с", "обл", "см", "км", "кг", "тобто",
    "e", "g", "i", "vs", "mr", "dr", "etc", "no", "н", "е", "пор", "гл", "ч", "пп",
}

APOSTROPHES = "'’ʼ`"
WORD_RE = re.compile(r"[A-Za-zА-Яа-яІіЇїЄєҐґ0-9]+(?:[" + APOSTROPHES + r"\-][A-Za-zА-Яа-яІіЇїЄєҐґ0-9]+)*")
NUMBER_RE = re.compile(r"\d")
SENT_END_RE = re.compile(r"([.!?…]+[\"»”)]*)(\s+)")


def normalize(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace(" ", " ")
    for a in APOSTROPHES[1:]:
        text = text.replace(a, "'")
    return text


def split_paragraphs(text: str) -> list[str]:
    text = normalize(text)
    parts = re.split(r"\n\s*\n", text)
    result = []
    for p in parts:
        p = re.sub(r"[ \t]*\n[ \t]*", " ", p).strip()
        if p and not re.fullmatch(r"[#*\-=_\s]+", p):
            result.append(p)
    return result


def split_sentences(text: str) -> list[str]:
    """Розбиває текст на речення з урахуванням поширених скорочень та ініціалів."""
    sentences: list[str] = []
    for para in split_paragraphs(text):
        start = 0
        for m in SENT_END_RE.finditer(para):
            end = m.end(1)
            candidate = para[start:end]
            # попереднє «слово» перед крапкою
            tail = re.search(r"([A-Za-zА-Яа-яІіЇїЄєҐґ]+)\.$", candidate)
            if tail and m.group(1) == ".":
                word = tail.group(1)
                nxt_char = para[m.end():m.end() + 1]
                # «і т.д.», «і т.п.», «та ін.» часто завершують речення: ріжемо, якщо далі велика літера
                ends_list = word.lower() in {"д", "п", "ін"} and nxt_char.isupper()
                if not ends_list and (word.lower() in ABBREVIATIONS or len(word) == 1 and word.isupper()):
                    continue
            nxt = para[m.end():m.end() + 1]
            if nxt and nxt.islower() and m.group(1) == ".":
                continue
            s = candidate.strip()
            if s:
                sentences.append(s)
            start = m.end()
        rest = para[start:].strip()
        if rest:
            sentences.append(rest)
    return sentences


def words(text: str) -> list[str]:
    return WORD_RE.findall(normalize(text))


def words_lower(text: str) -> list[str]:
    return [w.lower() for w in words(text)]


